def g(N):
    n = ''
    while N > 0:
        n = str(N % 5) + n
        N //= 5    # просто сокращенная запись
    return n

def f(N):
    n = g(N)
    if n[-1] == '0':
        r = '33' + n.replace('1', '*').replace('4', '1').replace('*', '4')    # сначала 1 заменяем на *, чтобы не запороть все
    else:
        r = '3' + n[1:] + '42'
    return int(r, 5)

a = []
for N in range(1,100000):
    if f(N) < 1922:
        a.append([-f(N),N]) # тут результат функции отрицателен, потому что надо найти минимальную N и максимальную f(N)
a.sort() # ставятся в порядке возрастания
print(a[0][1]) # модуля нет, потому что мы выводим N, а не результат функции
