# Запишите натуральное N в системе с основанием 5. Если запись
# оканчивается на 0, обменяйте в ней цифры 1 и 4 (каждое вхождение
# одной замените на другую) и допишите слева 33. Иначе допишите
# справа 42, а первый разряд замените на 3.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наибольшее возможное R, меньшее 1922, и укажите
# наименьшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def g(N):
    n = ''
    while N > 0:
        n = str(N % 5) + n
        N //= 5
    return n

def f(N):
    n = g(N)
    if n[-1] == '0':
        r = '33' + n.replace('1', '*').replace('4', '1').replace('*', '4')
    else:
        r = '3' + n[1:] + '42'
    return int(r, 5)

a = []
for N in range(1,100000):
    if f(N) < 1922:
        a.append([-f(N),N])
a.sort()
print(a[0][1])
