# Запишите натуральное N в системе с основанием 3. Если сумма цифр
# делится на 4, в записи обменяйте местами цифры 1 и 2
# (каждое вхождение одной замените на другую) и допишите слева 10.
# Иначе допишите справа 20 и замените второй и третий разряды
# полученной записи на 0 и 2 соответственно. Разряды считайте слева.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наименьшее возможное R, превышающее 302, и укажите
# наибольшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def g(N):
    n = ''
    while N > 0:
        n = str(N % 3) + n
        N //= 3
    return n

def f(N):
    n = g(N)
    if sum(map(int, n)) % 4 == 0:
        r = '10' + n.replace('1', '*').replace('2', '1').replace('*', '2')
    else:
        r = n[0] + '02' + n[3:] + '20'
    return int(r, 3)

a = []
for N in range(1,100000):
    if f(N) > 302:
        a.append([f(N), -N])

a.sort()
print(abs(a[0][1]))

