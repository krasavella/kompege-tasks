def g(N):
    n = ''
    while N > 0:
        n = str(N % 3) + n
        N //= 3    # просто сокращенная запись
    return n

def f(N):
    n = g(N)
    if sum(map(int, n)) % 4 == 0:    # я так записал сумму цифр числа n
        r = '10' + n.replace('1', '*').replace('2', '1').replace('*', '2')    # сначала 1 заменяем на *, чтобы не запороть все
    else:
        r = n[0] + '02' + n[3:] + '20'
    return int(r, 3)

a = []
for N in range(1,100000):
    if f(N) > 302:
        a.append([f(N), -N]) # тут N записывается отрицательным, чтобы при одинаковом f(N) первой была максимальная N

a.sort() # ставятся в порядке возрастания
print(abs(a[0][1]))    # В Python тоже есть модуль! я его использую там, где результат одной из переменной намеренно записывается отрицательным

