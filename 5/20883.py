# Запишите натуральное N в системе с основанием 5. Если длина записи
# нечётна, добавьте справа остаток от деления N на 5. Разделите
# полученную запись пополам и поменяйте половины местами.
# Это пятеричная запись результата R.
# Например, 21₁₀ = 41₅ преобразуется в 14₅ = 9₁₀.
# Найдите наименьшее N, для которого R > 50. Ответ дайте в десятичной системе.

def p(N):
    n = ''
    while N > 0:
        n = str(N % 5) + n
        N //= 5
    return n
def f(N):
    n = p(N)

