# Запишите натуральное N в системе с основанием 4. Если сумма цифр
# делится на 3, в записи обменяйте местами цифры 0 и 2
# (каждое вхождение одной замените на другую) и допишите слева 32.
# Иначе допишите справа 33 и замените второй и третий разряды
# полученной записи на 1 и 0 соответственно. Разряды считайте слева.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наименьшее возможное R, превышающее 320, и укажите
# наибольшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def g(N):
    n = ''
    while N > 0:
        n = str(N % 4) + n
        N //= 4
    return n

def f(N):
    n = g(N)
    if sum(map(int, n)) % 3 == 0:
        r = '32' + n.replace('0', '*').replace('2', '0').replace('*', '2')
    else:
        r = n[0] + '10' + n[3:] + '33'
    return int(r, 4)

a = []
for N in range(1,10000):
    if f(N) > 320:
        a.append([f(N), -N])
a.sort()
print(abs(a[0][1]))

