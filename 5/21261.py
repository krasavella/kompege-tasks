def g(N):
    n = ''
    while N > 0:
        n = str(N % 4) + n
        N //= 4    # просто сокращенная запись
    return n

def f(N):
    n = g(N)
    if sum(map(int, n)) % 3 == 0:    # я так записал сумму цифр числа n
        r = '32' + n.replace('0', '*').replace('2', '0').replace('*', '2')    # сначала 0 заменяем на *, чтобы не запороть все
    else:
        r = n[0] + '10' + n[3:] + '33'
    return int(r, 4)

a = []
for N in range(1,10000):
    if f(N) > 320:
        a.append([f(N), -N]) # тут N записывается отрицательным, чтобы при одинаковом f(N) первой была максимальная N
a.sort() # ставятся в порядке возрастания
print(abs(a[0][1]))    # В Python тоже есть модуль! я его использую там, где результат одной из переменной намеренно записывается отрицательным

