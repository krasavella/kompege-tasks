# Запишите натуральное N в двоичной системе и подсчитайте сумму цифр.
# Если сумма чётная, допишите справа 0 и замените два первых разряда
# на 10. Если сумма нечётная, допишите справа 1 и замените два первых
# разряда на 11. Итоговая двоичная запись задаёт R.
# Например, 6₁₀ = 110₂ даёт 1000₂ = 8₁₀, а 4₁₀ = 100₂ даёт 1101₂ = 13₁₀.
# Найдите наименьшее N, для которого R ≥ 16. Ответ дайте в десятичной системе.

def tr(N):
    n = ''
    while N > 0:
        n = str(N % 4) + n
        N // 4
    return n
        
def f(N):
    n = tr(N)
    if n[0] == '3':
        r = n.replace('1','3')
        r = n.replace('3', '1') + '21'
    else:
        r = '1' + n[1:] + '12'
    return int(r, 4)
for N in range (10000,0,-1):
    if f(N) < 598:
        print(N)
        break

