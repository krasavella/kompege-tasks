# Запишите натуральное N в троичной системе. Если N кратно 3, добавьте
# слева 1 и справа 02. Иначе умножьте остаток от деления N на 3 на число 5
# и допишите справа троичную запись произведения. Прочитайте результат
# как троичное число R и переведите его в десятичную систему.
# Например, 11₁₀ = 102₃ даёт 102101₃ = 307₁₀, а 12₁₀ = 110₃ даёт
# 111002₃ = 353₁₀. Найдите наименьшее N, для которого R ≥ 177.

def t(N):
    n = ''
    while N > 0:
        n = str(N % 3) + n
        N //= 3
    return n
def f(N):
    n = t(N)
    if N % 3 == 0:
        r = '1' + n + '02'
    else:
        r = n + t(N % 3 * 5)
    return int(r, 3)

for N in range(1,1000):
    if f(N) >= 177:
        print(N)
        break
