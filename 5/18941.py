# У четырёхзначного натурального числа умножают первую цифру на каждую
# из трёх остальных. Из трёх произведений берут два наибольших
# и приписывают большее к меньшему без разделителя.
# Например, для 2345 произведения равны 6, 8 и 10, результат — 810.
# Какое наименьшее исходное число даёт результат 5472?

from itertools import *
def f(N):
    m = []
    n = str(N)
    for i in range(1,4):
        m.append(int(n[0]) * int(n[i])) # записываем результаты произведения первой цифры с остальными в список
    s = sorted(m) # сортируем их по убыванию
    r = str(s[1]) + str(s[2])
    return int(r)
for N in range(1000,10000):
    if f(N) == 5472:
        print(N)
        break
