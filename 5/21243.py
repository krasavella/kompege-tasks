# Запишите натуральное N в системе с основанием 5. Если сумма цифр
# делится на 5, в записи обменяйте местами цифры 0 и 1
# (каждое вхождение одной замените на другую) и допишите справа 14.
# Иначе допишите справа 33 и замените первый и второй разряды
# полученной записи на 4 и 4 соответственно. Разряды считайте слева.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наименьшее возможное R, превышающее 370, и укажите
# наименьшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def p(N):
    n = ''
    while N > 0:
        n = str(N % 5) + n
        N //= 5
    return n
def f(N):
    n = p(N)
    if int(sum(map(int, str(n)))) % 5 == 0:
        r = n.replace('0', '*').replace('1','0').replace('*', '1') + '14'
    else:
        r = n[2:] + '33'
    return int(r, 5)
a = []
for N in range(1,1000):
    if f(N) > 370:
        a.append([f(N), N]) # тут в a добавляются связанные N и результат функции
a.sort() # ставятся в порядке возрастания
print(a[0][1])

