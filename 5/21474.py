# Запишите натуральное N в системе с основанием 6. Если сумма цифр
# делится на 5, в записи обменяйте местами цифры 0 и 3
# (каждое вхождение одной замените на другую) и допишите слева 11.
# Иначе допишите справа 44 и замените второй и третий разряды
# полученной записи на 0 и 5 соответственно. Разряды считайте слева.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наименьшее возможное R, превышающее 1500, и укажите
# наибольшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def g(N):
    n = ''
    while N > 0:
        n = str(N % 6) + n
        N //= 6
    return n

def f(N):
    n = g(N)
    if sum(map(int, n)) % 5 == 0:
        r = '11' + n.replace('0', '*').replace('3', '0').replace('*', '3')
    else:
        r = n[0] + '05' + n[3:] + '44'
    return int(r, 6)

a = []
for N in range(1,100000):
    if f(N) > 1500:
        a.append([f(N), -N])
a.sort()
print(abs(a[0][1]))

        
