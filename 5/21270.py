# Запишите натуральное N в системе с основанием 4. Если запись
# начинается на 3, обменяйте в ней цифры 1 и 3 (каждое вхождение
# одной замените на другую) и допишите слева 21. Иначе допишите
# справа 12, а первый разряд замените на 1.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наибольшее возможное R, меньшее 598, и укажите
# наибольшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def tr(N):
    n = ''
    while N > 0:
        n = str(N % 4) + n
        N //= 4
    return n
        
def f(N):
    n = tr(N)
    if n[0] == '3':
        r = n.replace('1','3')
        r = n.replace('3', '1') + '21'
    else:
        r = '1' + n[1:] + '12'
    return int(r, 4)
for N in range (10000,0,-1):
    if f(N) < 598:
        print(N)
        break

