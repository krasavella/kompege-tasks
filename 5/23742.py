# Запишите натуральное N в двоичной системе. Если N кратно 3, допишите
# справа три последние цифры этой записи. Иначе умножьте остаток
# от деления N на 3 на число 3 и допишите справа его двоичную запись.
# Полученную запись переведите в десятичную систему, чтобы получить R.
# Например, 12₁₀ = 1100₂ даёт 1100100₂ = 100₁₀, а 4₁₀ = 100₂
# даёт 10011₂ = 19₁₀. Найдите наименьшее N, для которого R ≥ 200.

def f(N):
    n = bin(N)[2:]
    if N % 3 == 0:
        r = n + n[-3:0]
    else:
        r = n + bin(N % 3 * 3)[2:]
    return int(r, 2)

for N in range(1,10000):
    if f(N) >= 200:
        print(N)
        break
