# Запишите натуральное N в системе с основанием 8. Если запись
# начинается на 5, обменяйте в ней цифры 1 и 2 (каждое вхождение
# одной замените на другую) и допишите слева 11. Иначе допишите
# справа 10, а первый разряд замените на 2.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наибольшее возможное R, меньшее 1354, и укажите
# наибольшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def f(N):
    n = oct(N)[2:]
    if n[0] == '5':
        r = n.replace('2', '1')
        r = '11' + n.replace('1', '2')
    else:
        
        r = '2' + n[1:] + '10'
    return int(r, 8)
for N in range(10000,0,-1):
    if f(N) < 1354:
        print(N, f(N))

