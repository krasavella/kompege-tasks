# Для пятизначного N обозначим через S сумму всех его цифр, через M —
# сумму наименьшей и наибольшей цифр, а через L и R — первую и последнюю
# цифры соответственно. Вычислите P₁ = S − L и P₂ = M − R. Запишите
# оба значения подряд без пробела в порядке неубывания, чтобы получить Z.
# Например, для N = 12502 получаем S = 10, M = 5, L = 1, R = 2,
# P₁ = 9 и P₂ = 3, откуда Z = 39.
# Найдите наибольшее N, при котором Z = 222.

def f(N):
    n = str(N)
    S = sum(map(int, str(N)))
    M = int(max(n)) + int(min(n))
    L = int(n[0])
    R = int(n[-1])
    p1 = S - L
    p2 = M - R
    if p1 >= p2:
        z = str(p2) + str(p1)
    else:
        z = str(p1) + str(p2)
    return int(z)
for N in range(100000,9999,-1):
    if f(N) == 222:
        print(N)
        break

