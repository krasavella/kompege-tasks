# Запишите натуральное N в двоичной системе. Для чётного N допишите
# по 11 с каждой стороны записи. Для нечётного N допишите 1 слева
# и 00 справа. Прочитайте результат как двоичное число R.
# Например, 13₁₀ = 1101₂ даёт 1110100₂ = 116₁₀,
# а 6₁₀ = 110₂ даёт 1111011₂ = 123₁₀.
# Найдите наибольшее возможное R, не превышающее 113. Ответ дайте
# в десятичной системе.

def f(N):
    n = bin(N)[2:]
    if N % 2 == 0:
        r = '11' + n + '11'
    else:
        r = '1' + n + '00'
    r = int(r, 2)
    return r
for N in range(10000,0,-1):
    if f(N) <= 113:
        print(f(N))
        break
