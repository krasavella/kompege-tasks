# Запишите натуральное N в системе с основанием 7. Если запись
# оканчивается на 2, обменяйте в ней цифры 1 и 3 (каждое вхождение
# одной замените на другую) и допишите слева 21. Иначе допишите
# справа 36, а первый разряд замените на 1.
# Прочитайте результат как число R в той же системе счисления.
# Найдите наибольшее возможное R, меньшее 744, и укажите
# наименьшее N, которое даёт такой результат. Ответ дайте в десятичной системе.

def s(N):
    n = ''
    while N > 0:
        n = str(N % 7) + n
        N //= 7
    return n
def f(N):
    n = s(N)
    if n[-1] == '2':
        r = '21' + n.replace('3', '*').replace('1', '3').replace('*', '1')
    else:
        r = '1' + n[1:] + '36'
    return int(r, 7)
a = []
for N in range(1,1000):
    if f(N) < 744:
        a.append([-f(N),N]) # тут результат функции отрицателен, потому что надо найти минимальную N и максимальную f(N)
a.sort()
print(a[0][1])

