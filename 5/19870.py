# Автомат записывает целое неотрицательное число в системе с основанием 4.
# Если число чётное, слева добавляется 12, а справа — четверичная
# запись утроенной последней цифры. Если число нечётное, слева
# добавляется 13, а справа — 21. Автомат выводит полученное число
# в десятичной системе. Какое наименьшее значение больше 50 он может вывести?

def tr(N):
    if N == 0:
        return '0'
    n = ''
    while N != 0:
        n = str(N % 4) + n
        N //= 4
    return n
        
def f(N):
    n = tr(N)
    if N % 2 == 0:
        r = '12' + n + tr(int(n[-1],4) * 3)
    else:
        r = '13' + n + '21'
    return int(r, 4)
for N in range(0,1000):
    if f(N) > 50:
        print(f(N))
        break
