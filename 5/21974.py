# Запишите натуральное N в двоичной системе. Для чётного N замените
# каждый 0 на 1. Для нечётного N замените все единицы, кроме первой,
# на пары 00. Полученная двоичная запись задаёт R, которое автомат
# выводит в десятичной системе. Например, 11₁₀ = 1011₂ даёт 100000₂ = 32₁₀.
# Среди возможных R, не превышающих 600, выберите наибольшее.
# Какое максимальное N даёт этот результат?

def f(N):
    n = bin(N)[2:]
    if N % 2 == 0:
        r = n.replace('0', '1')
    else:
        r = n[0] + n[1:].replace('1', '00')
    return int(r, 2)

a = []
for N in range(1,1000000):
    if f(N) <= 600:
        a.append([f(N), N])
a.sort()
print(a[-1][1])

