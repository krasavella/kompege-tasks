def f(N):
    n = bin(N)[2:]
    if N % 2 == 0:
        r = n.replace('0', '1')
    else:
        r = n[0] + n[1:].replace('1', '00') # здесь весьма тонкий момент, потому что первый символ в бинарнике - всегда единица. тонко)) действительно тонко)) не каждый поймет в чем здесь прикол))
    return int(r, 2)

a = []
for N in range(1,1000000):
    if f(N) <= 600:
        a.append([f(N), N]) # тут в a добавляются связанные N и результат функции
a.sort() # ставятся в порядке возрастания
print(a[-1][1])

