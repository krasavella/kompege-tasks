# Для серийных номеров деталей используют десятичные цифры и ещё
# 120 специальных символов. Каждый символ кодируют одинаковым
# минимальным числом бит. Для каждого номера в базе выделено
# одинаковое минимально необходимое целое число байт.
# Объём памяти для 12 755 226 номеров составляет не более 5 Гбайт.
# Определите наибольшую допустимую длину номера. Ответом служит целое число.

from math import *
N = 10 + 120
cnt = 12755226
mem = 5 * 1024 * 1024 * 1024
i = ceil(log2(N))
for len in range(1000,0,-1):
    if ceil(i * len / 8) * cnt <= mem:
        print(len)
        break
