# Для серийных номеров деталей используют десятичные цифры и ещё
# 510 специальных символов. Каждый символ кодируют одинаковым
# минимальным числом бит. Для каждого номера в базе выделено
# одинаковое минимально необходимое целое число байт.
# Объём памяти для 18 982 657 номеров составляет не менее 9379 Мбайт.
# Определите наименьшую допустимую длину номера. Ответом служит целое число.

from math import *
N = 10 + 510
cnt = 18982657
mem = 9379 * 1024**2
i = ceil(log2(N))
for len in range (1,1000):
    if ceil(i * len / 8) * cnt >= mem:
        print(len)
        break
