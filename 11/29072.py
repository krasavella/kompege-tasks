# Запись об объекте содержит код длиной L символов из алфавита
# мощностью 16 и порядковый номер записи. Все символы кодируются
# одинаковым минимальным числом бит. Для номеров используют двоичную
# запись одинаковой минимальной длины. На код и номер вместе
# выделяют минимально необходимое целое число байт.
# База из 8192 объектов занимает 4016 Кбайт. Определите наибольшее
# возможное L. В ответе укажите только число.

from math import *
N = 16
i = ceil(log2(N))
cnt = 8192
memall = 4016 * 1024
mem1 = ceil(memall / cnt)
for len in range(10000,0,-1):
    if ceil((i * len + 13) / 8) <= mem1:
        print(len)
        break
