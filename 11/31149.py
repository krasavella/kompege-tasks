# Серийный номер детали содержит 440 символов. Каждый символ
# кодируют одинаковым минимальным числом бит. Для каждого номера
# в базе выделено одинаковое минимально необходимое целое число байт.
# Объём памяти для 1 892 412 номеров составляет не менее 305 726 Кбайт.
# Определите наименьшую возможную мощность алфавита. Ответом служит целое число.

from math import *
cnt = 1892412
len = 440
mem = 305726 * 1024
for i in range(1,100):
    if ceil(i * len / 8) * cnt >= mem:
        print(2**(i - 1) + 1)
        break
