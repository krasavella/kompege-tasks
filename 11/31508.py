# Серийный номер детали содержит 157 символов. Каждый символ
# кодируют одинаковым минимальным числом бит. Для каждого номера
# в базе выделено одинаковое минимально необходимое целое число байт.
# Объём памяти для 12 450 номеров составляет не более 955 Кбайт.
# Определите наибольшую возможную мощность алфавита. Ответом служит целое число.

from math import *
N = 10 + 120
cnt = 12755226
mem = 5 * 1024 * 1024
i = log2(N)
for len in range(10000,0,-1):
    if (i * len / 8) * cnt <= mem:
        print(len)
        break
