# Серийный номер детали содержит 172 символов. Каждый символ
# кодируют одинаковым минимальным числом бит. Для каждого номера
# в базе выделено одинаковое минимально необходимое целое число байт.
# Объём памяти для 187 564 номеров составляет не более 39 Мбайт.
# Определите наибольшую возможную мощность алфавита. Ответом служит целое число.

from math import *
len = 172
cnt = 187564
mem = 39 * 1024**2
for i in range(10000,0,-1):
    if ceil(i * len / 8) * cnt <= mem:
        print(2**i)
