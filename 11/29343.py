# Идентификатор объекта состоит из 257 символов. Для его записи
# используют цифры системы с основанием 17 и ещё 4080 специальных
# символов. Каждый символ кодируют одинаковым минимальным числом бит.
# На каждый идентификатор выделяют одинаковое минимально необходимое
# целое число байт. Какой объём памяти в Мбайтах нужен для хранения
# 8 388 608 идентификаторов? В ответе укажите только целое число.

from math import *
len = 257
N = 4080 + 17
cnt = 8388608
i = ceil(log2(N))
mem1 = ceil(len * i / 8)
memall = mem1 * cnt
print(ceil(memall / (1024**2)))
