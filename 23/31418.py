# Команда A увеличивает число на 1. Команда B прибавляет к числу
# количество единиц в его двоичной записи. Программа — последовательность
# команд, а её траектория — результаты после каждой команды.
# Например, для AAB при старте с 5 траектория имеет вид 6, 7, 10.
# Сколько программ переводят число 5 в 40?

from functools import lru_cache
@lru_cache(None)
def f(a,b):
    if a > b: return 0
    if a == b: return 1
    s = bin(a)[2:]
    n = s.count('1')
    return f(a + 1,b) + f(a + n,b)
print(f(5,40))
