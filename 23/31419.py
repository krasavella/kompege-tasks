# Команда A прибавляет к числу 1. Команда B заменяет в его записи
# каждую цифру 1 на 3 и применима лишь при наличии хотя бы одной единицы.
# Программа — последовательность команд, а её траектория — результаты
# после каждой команды. Например, AAB при старте с 11 даёт 12, 13, 33.
# Сколько программ переводят 11 в 94 и используют B ровно три раза?

from functools import lru_cache
@lru_cache(None)
def f(a,b,k):
    if a > b: return 0
    if a == b and k == 3: return 1
    s = str(a)
    if s.count('1') >= 1: return f(a+1,b,k) + f(int(s.replace('1', '3')), b, k + 1)
    return f(a+1,b, k)
print(f(11,94,0))
