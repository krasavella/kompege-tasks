# Дана функция F = x ∧ (z → w) ∧ ¬y. Ниже три различные строки
# её таблицы истинности. Некоторые значения в них пропущены.
#
#  1 | 2 | 3 | 4 | F
# ---+---+---+---+---
#    |   | 1 |   | 1
#    | 1 | 0 |   | 1
#  1 | 0 |   |   | 1
#
# Определите, какая из переменных w, x, y, z соответствует каждому
# столбцу. Запишите буквы слева направо без разделителей.

print('x y w z')
for x in range(2):
    for y in range(2):
        for z in range(2):
            for w in range(2):
                f = (x and (z <= w) and not(y))
                if f == 1:
                    print(x,y,w,z)
