# Числа 761x035 и 338x932 записаны в системе с основанием 23.
# Вместо x в обоих числах стоит одна и та же неизвестная цифра.
# Найдите наименьшее x, при котором сумма этих чисел делится на 22.
# При найденном x запишите частное от деления суммы на 22
# в десятичной системе без указания основания.

from string import *
for x in (digits + ascii_uppercase)[:23]:
    a = int(f'761{x}035', 23) + int(f'338{x}932', 23)
    if a % 22 == 0:
        print(x, a // 22)
