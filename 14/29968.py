# Число 9 · 11²¹⁰ + 8 · 11¹⁵⁰ − x записали в системе с основанием 11,
# где x — целое число от 1 до 3000 включительно. Найдите наибольшее x,
# при котором в этой записи ровно 60 нулей. Ответ дайте в десятичной системе.

for x in range(3000, 0, -1):
    k = 0
    a = 9 * 11**210 + 8 * 11**150 - x
    while a > 0:
        if a % 11 == 0:
            k += 1
        a = a // 11
    if k == 60:
        print(x)
        break
