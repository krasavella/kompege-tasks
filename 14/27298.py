# Числа 871x291, 366x631 и 973x618 записаны в системе с основанием 40.
# Вместо x в каждом числе стоит одна и та же неизвестная цифра.
# Найдите наименьшее x, при котором сумма этих чисел делится на 39.
# При найденном x разделите сумму на 13 и запишите частное
# в десятичной системе без указания основания.

from string import *
def f(ishod):
    n = 0
    for c in ishod:
        n = n * 40 + int(c, 36)
    return n
for x in (digits + ascii_uppercase + ascii_lowercase)[:40]:
    a = f(f'871{x}291') + f(f'366{x}631') + f(f'973{x}618')
    if a % 39 == 0:
        print(x, a // 13)
