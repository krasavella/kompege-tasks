# Адрес сети получают побитовым И IP-адреса узла и маски. В широковещательном
# адресе все биты узла равны 1. Эти два адреса зарезервированы.
# Найдите адрес сети и укажите сумму его октетов. Например, для
# 100.20.3.4 ответом было бы 127.

