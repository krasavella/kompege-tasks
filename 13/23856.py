# Узел с IP-адресом 172.95.116.174 входит в сеть с маской 255.255.192.0.
# Адрес сети получают побитовым И адреса узла и маски. В широковещательном
# адресе все биты узла равны 1. Эти два адреса зарезервированы.
# Найдите наименьший IP-адрес в сети, у которого число единичных битов
# делится на 5. В ответе укажите сумму его октетов. Например, для адреса
# 100.10.3.4 такая сумма равна 117.

from ipaddress import *
net = ip_network('172.95.116.174/255.255.192.0',0)
for ip in net.hosts():
    if f'{int(ip):032b}'.count('1') % 5 == 0:
        print(ip)
        break
print(sum(map(int, str(ip).split('.'))))

