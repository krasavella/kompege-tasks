# Узел с IP-адресом 202.71.92.91 входит в сеть с маской 255.255.192.0.
# Адрес сети получают побитовым И адреса узла и маски. В широковещательном
# адресе все биты узла равны 1. Эти два адреса нельзя назначать компьютеру.
# Среди остальных адресов найдите наибольший с ровно двумя нечётными
# октетами. Запишите октеты подряд без точек, как 11122344 для 111.22.3.44.

from ipaddress import *
net = ip_network('202.71.92.91/255.255.192.0', 0)
for ip in net.hosts():
    i = str(ip).split('.')
    if sum(int(x) % 2 != 0 for x in i) == 2: # идет перебор октетов чтобы проверить их нечетность
        print(ip)
