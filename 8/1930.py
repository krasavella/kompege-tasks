# Ася составляет слова длины 7 из букв А, П, Е, Л, Ь, С, И, Н.
# Повторять буквы нельзя. Если в слове есть Ь, непосредственно
# слева и справа от него должны стоять согласные.
# Сколько разных слов можно составить?

from itertools import permutations
k = 0
for x in permutations('АПЕЛЬСИН', r = 7):
    s = ''.join(x)
    for y in 'ПЛСН':
        s = s.replace(y, 'С') # заменяем согласные на С для удобства
    if ('СЬС' in s) or ('Ь' not in s):
        k += 1
print(k)
